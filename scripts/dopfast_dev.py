#!/usr/bin/env python
"""dopfast usable-events attacker (evaluate.dopfast) on the fixed-wing DEV clips and the
synthetic set: detected and USABLE pass events per recording, before vs after cleaning, and
the pass criteria (unknown clock: <= 1 usable left; known clock: 0 usable left).

Outputs are recomputed with the CURRENT code by default (cached outputs go stale across
merges); --cached reuses .cache/baselines/<clip>__<method>.npy.

Usage:
  uv run python scripts/dopfast_dev.py                              # dopplerscrub only
  uv run python scripts/dopfast_dev.py --methods dopplerscrub bandstop_brick noise jitter
  uv run python scripts/dopfast_dev.py --only prop_pass air_p51_mustang --cached
Writes docs/results/dopfast_dev.json and docs/results/dopfast_dev.md.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

from dopplerscrub import evaluate as ev  # noqa: E402
import baselines as bl  # noqa: E402
import new_ridges as nr  # noqa: E402

RES = ROOT / "docs" / "results"


def fnum(v, d=1):
    return "–" if v is None or not np.isfinite(v) else f"{v:.{d}f}"


def clips_all(sets):
    out = []
    if "real" in sets:
        out += [dict(c, set="real") for c in nr.dev_real_clips()]     # fixed-wing dev; no heldout
    if "synth" in sets:
        out += [dict(c, set="synth") for c in bl.dev_clips() if c["set"] == "synth"]
    return out


def ev_str(evs):
    return "; ".join(f"{e['s']:.0f}s v{e['v']:.0f} d{e['d']:.0f}{'' if e['usable'] else ' (unusable)'}"
                     for e in evs) or "none"


def pm(v):
    return "n/a" if v is None else ("✓" if v else "✗")


def pt(vals):
    app = [v for v in vals if v is not None]
    return f"{sum(app)}/{len(app)}" if app else "n/a (none applicable)"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", nargs="*")
    ap.add_argument("--sets", nargs="*", default=["real", "synth"])
    ap.add_argument("--methods", nargs="*", default=["dopplerscrub"])
    ap.add_argument("--cached", action="store_true", help="reuse .cache/baselines outputs")
    ap.add_argument("--md-only", action="store_true", help="rewrite the markdown from the JSON")
    a = ap.parse_args(argv)
    try:
        rev = subprocess.run(["git", "-C", str(ROOT), "rev-parse", "--short", "HEAD"],
                             capture_output=True, text=True).stdout.strip()
    except Exception:
        rev = "?"
    rows = []
    for c in ([] if a.md_only else clips_all(a.sets)):
        if a.only and c["name"] not in a.only:
            continue
        x, sr = bl.load(c["path"])
        t0 = time.time()
        o = ev.dopfast_file(x, sr)
        print(f"== {c['name']}: {o['n_usable']} usable / {o['n_events']} events: {ev_str(o['events'])} "
              f"[{time.time() - t0:.0f}s]", flush=True)
        for m in a.methods:
            if a.cached:
                y, _ = bl.cached_apply(m, x, sr, c)
            else:
                y = bl.apply(m, x, sr, c)
                y = (np.round(np.clip(y, -1, 1) * 32767) / 32767).astype(np.float32)
            if y is None:
                continue
            n = min(len(x), len(y))
            r = ev.dopfast(x[:n], y[:n], sr, orig=o)
            rows.append({"clip": c["name"], "set": c["set"], "method": m, "rev": rev, **r})
            print(f"   {m:15s} {r['n_usable_clean']} usable / {r['n_events_clean']} events: "
                  f"{ev_str(r['events_clean'])}  pass unknown/known clock "
                  f"{r['pass_unknown_clock']}/{r['pass_known_clock']}", flush=True)
    jp = RES / "dopfast_dev.json"
    old = json.loads(jp.read_text()) if jp.exists() else []
    keys = {(r["clip"], r["method"]) for r in rows}
    rows = [r for r in old if (r["clip"], r["method"]) not in keys and "n_usable_orig" in r] + rows
    jp.write_text(json.dumps(rows, indent=1, default=float))
    L = ["# dopfast usable-events attacker: dev and synth clips", "",
         "Generated by `scripts/dopfast_dev.py` (`evaluate.dopfast`; method and frozen thresholds in "
         "docs/results/dopfast.md). An **event** is a grouped peak of the evidence volume E[v, d, s] "
         f"above tau = {ev.DF_EVENT_TAU:g} (null false-alarm rate ~0.3/min); it is **usable** if its "
         "(v, d) profile pins d to <= 4x. Pass criteria after cleaning: **unknown clock** = <= 1 usable "
         "event left (nothing to intersect); **known clock** = 0 usable left.", "",
         "| clip | set | method | code | usable / events orig → clean | pass unknown / known clock | orig events | clean events |",
         "|---|---|---|---|---|---|---|---|"]
    for r in sorted(rows, key=lambda r: (r["set"], r["clip"], r["method"])):
        L.append(f"| {r['clip']} | {r['set']} | {r['method']} | {r.get('rev', '?')} | "
                 f"{r['n_usable_orig']}/{r['n_events_orig']} → {r['n_usable_clean']}/{r['n_events_clean']} | "
                 f"{pm(r['pass_unknown_clock'])} / {pm(r['pass_known_clock'])} | "
                 f"{ev_str(r['events_orig'])} | {ev_str(r['events_clean'])} |")
    for st in ("real", "synth"):
        for m in sorted({r["method"] for r in rows}):
            rs = [r for r in rows if r["method"] == m and r["set"] == st]
            if rs:
                L += ["", f"**{st} / {m}** ({len(rs)} clips): usable events {sum(r['n_usable_orig'] for r in rs)} → "
                      f"{sum(r['n_usable_clean'] for r in rs)}; pass unknown clock {pt([r['pass_unknown_clock'] for r in rs])}, "
                      f"known clock {pt([r['pass_known_clock'] for r in rs])} (clips where the criterion applies: "
                      "the original had >= 2 / >= 1 usable events)."]
    (RES / "dopfast_dev.md").write_text("\n".join(L) + "\n")
    print(f"wrote {RES / 'dopfast_dev.md'}")


if __name__ == "__main__":
    main()
